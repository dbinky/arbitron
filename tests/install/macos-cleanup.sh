#!/usr/bin/env bash
#
# macos-cleanup.sh — reset a macOS host to a pre-install state so the Arbitron
# macOS installer (install.sh, local/per-user profile) can be tested "fresh"
# again and again.
#
# What it does:
#   1. Stops any running `arbitron serve` processes (dev `./arbitron serve`,
#      tmp test builds, and an installed service wrapper).
#   2. Boots out + removes the launchd LaunchAgent (~/Library/LaunchAgents/
#      dev.arbitron.plist) if present.
#   3. Backs up the hand-maintained dev config (~/.arbitron/config.yaml — model
#      profiles + claude-cli provider) to ~/.arbitron-devconfig-backups/ BEFORE
#      wiping, since it is not regenerated by the installer.
#   4. Removes the per-user install tree ~/.arbitron entirely.
#   5. Removes the shared-profile binary (/usr/local/bin/arbitron) if present.
#
# What it intentionally leaves alone:
#   - The repo working tree, including the locally built ./arbitron binary and
#     ./arbitron.db. Those are build artifacts, not installer footprint.
#
# Usage:
#   tests/install/macos-cleanup.sh           # do the cleanup
#   DRY_RUN=1 tests/install/macos-cleanup.sh # print what it would do
#
# To restore the dev config after a fresh-install test:
#   cp ~/.arbitron-devconfig-backups/config.yaml.<timestamp> ~/.arbitron/config.yaml
set -euo pipefail

LABEL="dev.arbitron"
PLIST="$HOME/Library/LaunchAgents/${LABEL}.plist"
ARB_HOME="$HOME/.arbitron"
SHARED_BIN="/usr/local/bin/arbitron"
BACKUP_DIR="$HOME/.arbitron-devconfig-backups"

run() {
  if [ -n "${DRY_RUN:-}" ]; then
    printf '[dry-run] %s\n' "$*"
  else
    printf '+ %s\n' "$*"
    eval "$@"
  fi
}

echo "== 1. Stop running arbitron serve processes =="
# Match the installed service wrapper, dev `./arbitron serve`, and tmp test builds.
pids="$(pgrep -f 'arbitron serve' 2>/dev/null || true)"
if [ -n "$pids" ]; then
  for pid in $pids; do
    run "kill $pid 2>/dev/null || true"
  done
  sleep 1
  # Escalate to SIGKILL for any survivors.
  pids="$(pgrep -f 'arbitron serve' 2>/dev/null || true)"
  [ -n "$pids" ] && for pid in $pids; do run "kill -9 $pid 2>/dev/null || true"; done
else
  echo "  (no arbitron serve processes running)"
fi

echo "== 2. Unload + remove launchd LaunchAgent =="
if launchctl list 2>/dev/null | grep -q "$LABEL"; then
  uid="$(id -u)"
  run "launchctl bootout gui/${uid}/${LABEL} 2>/dev/null || launchctl unload -w '$PLIST' 2>/dev/null || true"
else
  echo "  (no $LABEL agent loaded)"
fi
if [ -f "$PLIST" ]; then
  run "rm -f '$PLIST'"
else
  echo "  (no plist at $PLIST)"
fi

echo "== 3. Back up dev config (model profiles) =="
if [ -f "$ARB_HOME/config.yaml" ]; then
  ts="$(date +%Y%m%d-%H%M%S)"
  run "mkdir -p '$BACKUP_DIR'"
  run "cp -p '$ARB_HOME/config.yaml' '$BACKUP_DIR/config.yaml.$ts'"
  echo "  backed up to $BACKUP_DIR/config.yaml.$ts"
else
  echo "  (no $ARB_HOME/config.yaml to back up)"
fi

echo "== 4. Remove per-user install tree ~/.arbitron =="
if [ -d "$ARB_HOME" ]; then
  run "rm -rf '$ARB_HOME'"
else
  echo "  (no $ARB_HOME)"
fi

echo "== 5. Remove shared-profile binary =="
if [ -e "$SHARED_BIN" ]; then
  run "sudo rm -f '$SHARED_BIN'"
else
  echo "  (no $SHARED_BIN)"
fi

echo
echo "Cleanup complete — host is in a pre-install state for the macOS installer."
